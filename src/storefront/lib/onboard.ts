/**
 * Pure functions of the redeem page: normalising, validating and generating redeem codes, usernames and passwords.
 * The rules for redeem codes, usernames, passwords and notification addresses match mailhq (src/lib/cdk/rules.ts, src/lib/username.ts, src/lib/mailbox/input.ts,
 * src/lib/onboard/input.ts); this only catches obviously invalid input early in the browser, the server has the final say.
 * Both sides test these values against docs/onboard-contract.json (tests/contract.test.ts); change both sides and both files together.
 * This file does not depend on the DOM and must not use TypeScript syntax Node cannot run directly (enum, parameter properties); tests/ runs it as is.
 */

/** Redeem code: 16 characters, displayed in groups of 4 separated by hyphens; generated by mailhq with an alphabet that drops the confusable 0 / O and 1 / I. */
export const CDK_LENGTH = 16;
export const CDK_GROUP = 4;
export const CDK_ALPHABET = "23456789ABCDEFGHJKLMNPQRSTUVWXYZ";

/** Strips spaces, hyphens and everything else non-alphanumeric, upper-cases, keeps at most 16 characters. */
export function normalizeCdk(raw: string): string {
  return raw
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, "")
    .slice(0, CDK_LENGTH);
}

/** Display form in the input: XXXX-XXXX-XXXX-XXXX (while half typed, only the existing part is grouped). */
export function formatCdk(raw: string): string {
  const groups = normalizeCdk(raw).match(new RegExp(`.{1,${CDK_GROUP}}`, "g"));
  return groups ? groups.join("-") : "";
}

export function isCdkComplete(raw: string): boolean {
  return normalizeCdk(raw).length === CDK_LENGTH;
}

/** Mailbox local part: lower-case letters, digits and . _ -, must start and end with a letter or digit, no two dots in a row, at most 64 characters (same as mailhq). */
export const MAX_LOCAL_PART_LENGTH = 64;
export const LOCAL_PART_PATTERN = /^[a-z0-9](?:(?:[a-z0-9_-]|\.(?!\.)){0,62}[a-z0-9])?$/;

/** Trims whitespace and lower-cases; when a full address is pasted, drops @ and what follows. */
export function normalizeUsername(raw: string): string {
  const value = raw.trim().toLowerCase();
  const at = value.indexOf("@");
  return at === -1 ? value : value.slice(0, at);
}

export type UsernameProblem = "required" | "invalid";

/** What is wrong with a normalised username; null when nothing is. */
export function usernameProblem(username: string): UsernameProblem | null {
  if (!username) return "required";
  if (username.length > MAX_LOCAL_PART_LENGTH || !LOCAL_PART_PATTERN.test(username)) return "invalid";
  return null;
}

/** Password rules of a Stalwart mailbox: 8 to 128 characters, no whitespace. */
export const PASSWORD_MIN_LENGTH = 8;
export const PASSWORD_FIELD_MAX = 128;
export const PASSWORD_GENERATED_LENGTH = 16;

export interface PasswordChecks {
  length: boolean;
}

export const PASSWORD_RULES = ["length"] as const;
export type PasswordRule = (typeof PASSWORD_RULES)[number];

export function passwordChecks(password: string): PasswordChecks {
  return {
    length: password.length >= PASSWORD_MIN_LENGTH,
  };
}

export type PasswordProblem = "required" | "too_long" | "whitespace" | "weak";

export function passwordProblem(password: string): PasswordProblem | null {
  if (!password) return "required";
  if (password.length > PASSWORD_FIELD_MAX) return "too_long";
  if (/\s/.test(password)) return "whitespace";
  if (!passwordChecks(password).length) return "weak";
  return null;
}

/* Random password: the same alphabet as mailhq's generator (without 0/O, 1/l/I), with at least one of each of the three character classes. */
const LOWER = "abcdefghijkmnpqrstuvwxyz";
const UPPER = "ABCDEFGHJKLMNPQRSTUVWXYZ";
const DIGITS = "23456789";
export const PASSWORD_ALPHABET = LOWER + UPPER + DIGITS;

/** Uniform random integer in [0, n): rejection sampling, to avoid modulo bias. */
function randomInt(n: number): number {
  const limit = Math.floor(0x1_0000_0000 / n) * n;
  const buffer = new Uint32Array(1);
  let value: number;
  do {
    globalThis.crypto.getRandomValues(buffer);
    value = buffer[0]!;
  } while (value >= limit);
  return value % n;
}

function pick(alphabet: string): string {
  return alphabet[randomInt(alphabet.length)]!;
}

export function generatePassword(length = PASSWORD_GENERATED_LENGTH): string {
  const size = Math.max(PASSWORD_MIN_LENGTH, Math.min(PASSWORD_FIELD_MAX, Math.trunc(length)));
  const chars = [pick(LOWER), pick(UPPER), pick(DIGITS)];
  while (chars.length < size) chars.push(pick(PASSWORD_ALPHABET));
  for (let i = chars.length - 1; i > 0; i--) {
    const j = randomInt(i + 1);
    [chars[i], chars[j]] = [chars[j]!, chars[i]!];
  }
  return chars.join("");
}

/** Generates a random redeem code (only the mock API and tests use it; in production mailhq generates them). */
export function generateCdk(): string {
  let code = "";
  while (code.length < CDK_LENGTH) code += pick(CDK_ALPHABET);
  return code;
}

/** Maximum number of mailboxes in one activation request (same as mailhq's REDEEM_MAX_MAILBOXES). */
export const REDEEM_MAX_MAILBOXES = 20;

/** Which password requirements are still missing (in PASSWORD_RULES order); empty when all are met. */
export function passwordMissing(password: string): PasswordRule[] {
  const checks = passwordChecks(password);
  return PASSWORD_RULES.filter((rule) => !checks[rule]);
}

export function emailAddress(username: string, domain: string): string {
  return `${username}@${domain}`;
}

/**
 * Address that receives the account details (optional): any address that can receive mail. Only the most basic shape is checked (exactly one @, non-empty on both sides, a dot in the domain)
 * plus the RFC 5321 length limits; whether the address is right is really tested by whether the mail arrives. The same rules as mailhq's parseNotify.
 */
export const NOTIFY_EMAIL_MAX = 254;
export const NOTIFY_EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

/** Trims whitespace and lower-cases: addresses are case-insensitive, so display and sending use one form. */
export function normalizeEmail(raw: string): string {
  return raw.trim().toLowerCase();
}

export type NotifyProblem = "invalid" | "too_long";

/** What is wrong with a normalised notification address; the empty string also counts as invalid, whether the field is optional is the caller's decision. */
export function notifyProblem(email: string): NotifyProblem | null {
  if (email.length > NOTIFY_EMAIL_MAX) return "too_long";
  if (!NOTIFY_EMAIL_PATTERN.test(email)) return "invalid";
  return null;
}
