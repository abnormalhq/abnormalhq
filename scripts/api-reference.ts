/**
 * Writes src/content/developers/reference.ts from public/developers/openapi.json (see src/lib/api-reference.ts).
 * Run after copying a new docs/openapi.json from abnormalhq/mail:
 *
 *   cp ../mail/docs/openapi.json public/developers/openapi.json
 *   pnpm api-reference
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildApiReference } from "../src/lib/api-reference.ts";

const source = fileURLToPath(new URL("../public/developers/openapi.json", import.meta.url));
const target = fileURLToPath(new URL("../src/content/developers/reference.ts", import.meta.url));

const reference = buildApiReference(JSON.parse(readFileSync(source, "utf8")));
writeFileSync(
  target,
  [
    "/**",
    " * Generated by `pnpm api-reference` from public/developers/openapi.json, a copy of abnormalhq/mail docs/openapi.json.",
    " * Do not edit by hand: tests/developers-page.test.ts fails while this differs from the copy.",
    " */",
    'import type { ApiReference } from "../../lib/api-reference.ts";',
    "",
    `export const apiReference: ApiReference = ${JSON.stringify(reference)};`,
    "",
  ].join("\n"),
);
execFileSync("prettier", ["--write", target], { stdio: "inherit" });
