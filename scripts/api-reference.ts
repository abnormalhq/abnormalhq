/**
 * Writes the developer page's endpoint list (src/content/developers/reference.ts) and the downloadable specification
 * (public/developers/openapi.json) from docs/openapi.json, the copy of mail's document (see src/lib/api-reference.ts).
 * Run after copying a new docs/openapi.json from abnormalhq/mail:
 *
 *   cp ../mail/docs/openapi.json docs/openapi.json
 *   pnpm api-reference
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { developerApi } from "../src/data/site.ts";
import { buildApiReference, publicOpenApiDocument, serializeJson } from "../src/lib/api-reference.ts";

const file = (path: string) => fileURLToPath(new URL(`../${path}`, import.meta.url));
const source = file("docs/openapi.json");
const reference = file("src/content/developers/reference.ts");
const published = file("public/developers/openapi.json");

const document = JSON.parse(readFileSync(source, "utf8"));
writeFileSync(
  reference,
  [
    "/**",
    " * Generated by `pnpm api-reference` from docs/openapi.json, a copy of abnormalhq/mail docs/openapi.json.",
    " * Do not edit by hand: tests/developers-page.test.ts fails while this differs from the copy.",
    " */",
    'import type { ApiReference } from "../../lib/api-reference.ts";',
    "",
    `export const apiReference: ApiReference = ${JSON.stringify(buildApiReference(document))};`,
    "",
  ].join("\n"),
);
execFileSync("prettier", ["--write", reference], { stdio: "inherit" });

mkdirSync(dirname(published), { recursive: true });
writeFileSync(published, serializeJson(publicOpenApiDocument(document, developerApi.base)));
